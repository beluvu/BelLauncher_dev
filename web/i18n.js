// Текст из Python приходит по-русски: если такая фраза есть в словаре, показываем перевод
// Ключи pfx_* — начало динамического сообщения (после него Python дописывает имя, число и т.п.)
function trMsg(s) {
  if (!s || LANG === 'ru') return s;
  const exact = Object.keys(I18N.ru).find((x) => I18N.ru[x] === s);
  if (exact) return tr(exact);
  let best = null;
  for (const k of Object.keys(I18N.ru)) {
    if (!k.startsWith('pfx_')) continue;
    const pre = I18N.ru[k];
    if (s.startsWith(pre) && (!best || pre.length > I18N.ru[best].length)) best = k;
  }
  return best ? tr(best) + s.slice(I18N.ru[best].length) : s;
}
